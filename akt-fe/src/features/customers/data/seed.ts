function customerNumberFromDate(date: Date) {
  return [
    String(date.getFullYear()).slice(-2),
    String(date.getMonth() + 1).padStart(2, "0"),
    String(date.getDate()).padStart(2, "0"),
    String(date.getHours()).padStart(2, "0"),
    String(date.getMinutes()).padStart(2, "0"),
    String(date.getSeconds()).padStart(2, "0"),
  ].join("");
}

export function nextCustomerNumber(customers: Customer[]) {
  const used = new Set(customers.map((customer) => customer.customerNumber));
  const date = new Date();
  let candidate = customerNumberFromDate(date);

  while (used.has(candidate)) {
    date.setSeconds(date.getSeconds() + 1);
    candidate = customerNumberFromDate(date);
  }

  return candidate;
}

export function isCustomerNumber(value: string) {
  return /^\d{12}$/.test(value);
}

export function customerNumberFromDateString(value: string, index: number) {
  const digits = value.replace(/\D/g, "").padEnd(8, "0");
  const date = `${digits.slice(2, 4)}${digits.slice(4, 6)}${digits.slice(6, 8)}`;
  return `${date}${String(index + 1).padStart(6, "0")}`;
}
